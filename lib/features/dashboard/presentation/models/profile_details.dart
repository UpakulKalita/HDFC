class ProfileDetails {
  final String name;
  final String email;
  final String maritialStatus;
  final String occupation;
  final String age;
  final String city;
  final String gender;
  final String dependents;

  ProfileDetails({
    required this.name,
    required this.email,
    required this.maritialStatus,
    required this.occupation,
    required this.age,
    required this.city,
    required this.gender,
    required this.dependents,
  });
}
